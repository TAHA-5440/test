export const DISEASE_MAP: Record<string, Disease> = DISEASES.reduce(
  (acc, d) => {
    acc[d.id] = d;
    return acc;
  },
  {} as Record<string, Disease>,
);

export function diseasesForSpecies(species: string): Disease[] {
  return DISEASES.filter((d) => d.species.includes(species as Disease['species'][number]));
}

export function searchDiseases(query: string): Disease[] {
  const q = query.trim().toLowerCase();
  if (!q) return DISEASES;
  return DISEASES.filter((d) => {
    if (d.name.toLowerCase().includes(q)) return true;
    if (d.aka.some((a) => a.toLowerCase().includes(q))) return true;
    if (d.system.toLowerCase().includes(q)) return true;
    return d.summary.toLowerCase().includes(q);
  });
}
